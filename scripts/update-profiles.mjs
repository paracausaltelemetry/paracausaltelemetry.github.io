import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/*
 * TryHackMe and Hack The Box profile cards on the Writeups page.
 *
 *   node scripts/update-profiles.mjs --fetch [--thm-file thm.json]
 *                                             read both public profiles,
 *                                             save data/profiles.json, render
 *   node scripts/update-profiles.mjs           render the cards from the JSON
 *   node scripts/update-profiles.mjs --check   CI: fail if the page is stale
 *
 * The daily workflow (.github/workflows/profiles.yml) runs --fetch and commits
 * any change. TryHackMe has a public JSON profile, but its bot protection
 * answers plain HTTP clients with 429, so the workflow fetches it through a
 * headless browser (scripts/fetch-thm-profile.py) and passes the file here; Hack The Box's new profile
 * has no stats or badge, so its card lists the CTF event certificates read
 * from the public profile page. If either source fails or changes shape, the
 * last good data is kept and the run says so.
 */

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DATA = resolve(ROOT, "data", "profiles.json");
const PAGE = resolve(ROOT, "writeups", "index.html");
const FETCH = process.argv.includes("--fetch");
const CHECK = process.argv.includes("--check");
const THM_FILE = process.argv.includes("--thm-file") ? process.argv[process.argv.indexOf("--thm-file") + 1] : null;

const THM = { username: "ParacausalTelemetry", url: "https://tryhackme.com/p/ParacausalTelemetry" };
const HTB = { handle: "ParacausalTelemetry", url: "https://profile.hackthebox.com/profile/019d5e35-f9f2-73c9-89fd-762d0cd0d177" };
const START = "<!-- profiles:start (generated by scripts/update-profiles.mjs; do not edit) -->";
const END = "<!-- profiles:end -->";
const UA = "Mozilla/5.0 (compatible; paracausaltelemetry-profiles/1.0; +https://paracausaltelemetry.com/)";

const esc = (value = "") => String(value)
  .replaceAll("&", "&amp;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;")
  .replaceAll('"', "&quot;")
  .replaceAll("'", "&#39;");
const decode = (value) => value
  .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
  .replaceAll("&quot;", '"').replaceAll("&#39;", "'").replaceAll("&lt;", "<").replaceAll("&gt;", ">").replaceAll("&amp;", "&");
const number = (n) => Number(n).toLocaleString("en-GB");
const dateDisplay = (iso) => new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" }).format(new Date(`${iso}T00:00:00Z`));

/* ---------- fetch ---------- */
async function fetchThm() {
  let json;
  if (THM_FILE) {
    if (!existsSync(THM_FILE)) throw new Error(`TryHackMe: ${THM_FILE} not found (browser fetch failed?)`);
    json = JSON.parse(readFileSync(THM_FILE, "utf8"));
  } else {
    const response = await fetch(`https://tryhackme.com/api/v2/public-profile?username=${encodeURIComponent(THM.username)}`, { headers: { "user-agent": UA, accept: "application/json" } });
    if (!response.ok) throw new Error(`TryHackMe HTTP ${response.status}`);
    json = await response.json();
  }
  const { data } = json;
  for (const key of ["username", "rank", "topPercentage", "leagueTier", "level", "completedRoomsNumber", "badgesNumber"]) {
    if (data?.[key] === undefined || data[key] === null) throw new Error(`TryHackMe profile has no ${key}`);
  }
  return {
    username: data.username,
    rank: data.rank,
    topPercentage: data.topPercentage,
    league: data.leagueTier,
    level: data.level,
    rooms: data.completedRoomsNumber,
    badges: data.badgesNumber
  };
}

async function fetchHtb() {
  const response = await fetch(HTB.url, { headers: { "user-agent": UA, accept: "text/html" } });
  if (!response.ok) throw new Error(`Hack The Box HTTP ${response.status}`);
  const html = await response.text();
  /* each event certificate is an li.internal-certification: a heading with
     the event name, then "HTB CTF · Mon YYYY" */
  const events = [];
  for (const block of html.split(/<li[^>]*class="[^"]*internal-certification[^"]*"/).slice(1)) {
    const item = block.split("</li>")[0];
    const name = item.match(/class="[^"]*htb-heading-xs[^"]*">([^<]+)</)?.[1];
    const meta = [...item.matchAll(/<div>([^<]+)<\/div>/g)].map((m) => decode(m[1]).trim());
    if (name) events.push({ name: decode(name).trim(), kind: meta[0] || "", date: meta[meta.length - 1] || "" });
  }
  if (!events.length) throw new Error("Hack The Box profile: no event certificates found (page layout changed?)");
  if (!html.includes(`@${HTB.handle}`)) throw new Error("Hack The Box profile: handle not found");
  return { handle: HTB.handle, events };
}

/* ---------- render ---------- */
const stat = (label, value) => `<div><dt>${esc(label)}</dt><dd>${esc(value)}</dd></div>`;

const render = (data) => {
  const thm = data.tryhackme, htb = data.hackthebox;
  const cards = [];
  if (thm) cards.push(`<li><a class="profile-card" href="${esc(THM.url)}" target="_blank" rel="me noopener noreferrer">
                  <span class="profile-card-head"><img src="/src/logo-thm.jpg" width="36" height="36" alt="" /><span><strong>TryHackMe</strong><small>@${esc(thm.username)}</small></span></span>
                  <dl class="profile-stats">${stat("Rank", `Top ${thm.topPercentage}%`)}${stat("League", thm.league.charAt(0).toUpperCase() + thm.league.slice(1))}${stat("Rooms", number(thm.rooms))}${stat("Badges", number(thm.badges))}</dl>
                  <span class="visually-hidden"> (opens in a new tab)</span>
                </a></li>`);
  if (htb) cards.push(`<li><a class="profile-card" href="${esc(HTB.url)}" target="_blank" rel="me noopener noreferrer">
                  <span class="profile-card-head"><img src="/src/logo-htb.png" width="36" height="36" alt="" /><span><strong>Hack The Box</strong><small>@${esc(htb.handle)}</small></span></span>
                  <ul class="profile-events" aria-label="CTF events">${htb.events.slice(0, 3).map((e) => `<li><span>${esc(e.name)}</span><small>${esc(e.date)}</small></li>`).join("")}</ul>
                  <span class="visually-hidden"> (opens in a new tab)</span>
                </a></li>`);
  return `${START}
              <ul class="profile-cards" aria-label="Platform profiles">
                ${cards.join("\n                ")}
              </ul>
              <p class="profile-note">From my public profiles, checked daily. Last changed ${esc(dateDisplay(data.updated))}.</p>
              ${END}`;
};

/* ---------- main ---------- */
const previous = existsSync(DATA) ? JSON.parse(readFileSync(DATA, "utf8")) : {};
let data = previous;

if (FETCH) {
  const next = { ...previous };
  const results = await Promise.allSettled([fetchThm(), fetchHtb()]);
  const [thm, htb] = results;
  if (thm.status === "fulfilled") next.tryhackme = thm.value; else console.warn(`  WARN ${thm.reason.message}; keeping the last TryHackMe data`);
  if (htb.status === "fulfilled") next.hackthebox = htb.value; else console.warn(`  WARN ${htb.reason.message}; keeping the last Hack The Box data`);
  const strip = ({ updated, ...rest }) => JSON.stringify(rest);
  if (strip(next) !== strip(previous)) {
    next.updated = new Date().toISOString().slice(0, 10);
    writeFileSync(DATA, `${JSON.stringify({ updated: next.updated, tryhackme: next.tryhackme, hackthebox: next.hackthebox }, null, 2)}\n`, "utf8");
    console.log("Profiles: data changed, data/profiles.json written.");
  } else {
    console.log("Profiles: no change.");
  }
  data = next.updated ? next : previous;
  if (results.every((r) => r.status === "rejected") && !previous.updated) process.exit(1);
}

if (!data.updated) {
  console.error("  FAIL data/profiles.json is missing; run node scripts/update-profiles.mjs --fetch");
  process.exit(1);
}

const page = readFileSync(PAGE, "utf8");
const crlf = page.includes("\r\n");
const text = page.replace(/\r\n/g, "\n");
const from = text.indexOf(START), to = text.indexOf(END);
if (from === -1 || to === -1) {
  console.error(`  FAIL ${relative(ROOT, PAGE)}: profiles markers not found`);
  process.exit(1);
}
const updatedPage = text.slice(0, from) + render(data) + text.slice(to + END.length);
if (CHECK) {
  if (updatedPage !== text) {
    console.error(`  FAIL ${relative(ROOT, PAGE)}: profile cards are stale. Run node scripts/update-profiles.mjs`);
    process.exit(1);
  }
  console.log("Profiles: writeups page checked.");
} else if (updatedPage !== text) {
  writeFileSync(PAGE, crlf ? updatedPage.replace(/\n/g, "\r\n") : updatedPage, "utf8");
  console.log(`Profiles: ${relative(ROOT, PAGE)} updated.`);
} else {
  console.log("Profiles: writeups page already current.");
}
